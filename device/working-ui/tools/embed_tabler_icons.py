#!/usr/bin/env python3
"""Convert official Tabler filled SVGs to embedded PNG C++ arrays."""

import pathlib
import subprocess
import sys
import tempfile

ASSET_DIR = pathlib.Path(__file__).resolve().parent.parent / "assets" / "tabler-filled"

ICONS = {
    "gamepad": "device-gamepad-2.svg",
    "music": "file-music.svg",
    "movies": "device-tv-old.svg",
    "tv": "device-tv.svg",
}

def main():
    if len(sys.argv) != 2:
        print(f"Usage: {sys.argv[0]} OUTPUT_HEADER", file=sys.stderr)
        return 2

    output = pathlib.Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)

    if not ASSET_DIR.is_dir():
        print(f"Missing Tabler asset directory: {ASSET_DIR}", file=sys.stderr)
        return 1

    arrays = []
    with tempfile.TemporaryDirectory(prefix="kiddos-tabler-") as temp:
        temp_dir = pathlib.Path(temp)

        for name, filename in ICONS.items():
            source = ASSET_DIR / filename
            if not source.is_file():
                print(f"Missing icon: {source}", file=sys.stderr)
                return 1

            svg = source.read_text(encoding="utf-8")
            if 'fill="currentColor"' not in svg:
                print(f"Unexpected SVG fill in {source}", file=sys.stderr)
                return 1

            # Preserve the original SVG; apply the UI blue only to the
            # temporary rasterization input.
            colored_svg = temp_dir / filename
            colored_svg.write_text(
                svg.replace('fill="currentColor"', 'fill="#50beff"'),
                encoding="utf-8",
            )

            png = temp_dir / f"{name}.png"
            subprocess.run(
                ["rsvg-convert", "--width", "96", "--height", "96",
                 "--output", str(png), str(colored_svg)],
                check=True,
            )

            data = png.read_bytes()
            if not data.startswith(b"\x89PNG\r\n\x1a\n"):
                print(f"Invalid PNG output for {filename}", file=sys.stderr)
                return 1

            values = ", ".join(f"0x{byte:02x}" for byte in data)
            arrays.append(
                f"inline constexpr unsigned char {name}[] = "
                f"{{{values}}};\n"
                f"inline constexpr std::size_t {name}_size = sizeof({name});"
            )
            print(f"{filename}: {len(data)} PNG bytes")

    content = (
        "// Generated by tools/embed_tabler_icons.py; do not edit.\n"
        "#pragma once\n"
        "#include <cstddef>\n\n"
        "namespace TablerIcons {\n"
        + "\n\n".join(arrays)
        + "\n}\n"
    )

    output.write_text(content, encoding="utf-8")
    print(f"Generated: {output}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
